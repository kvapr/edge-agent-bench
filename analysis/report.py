#!/usr/bin/env python3
"""Compute every number, table and figure input used in docs/REPORT.md.

Runs each report module on a results directory and writes one JSON file with
all of their outputs and one Markdown file with all of their tables:

    python3 analysis/report.py results/v2 --json analysis/out/report.json \\
        --md analysis/out/report_tables.md

Each module (analysis/report_<name>.py) exposes compute(results_dir) -> dict
and tables_md(data) -> str, and can also be run on its own.
"""
import argparse
import importlib
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

MODULES = ("accuracy", "errors", "robustness", "speed", "stack", "v1v2")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("results_dir")
    ap.add_argument("--json", required=True)
    ap.add_argument("--md", required=True)
    ap.add_argument("--only", default="", help="comma-separated module names")
    a = ap.parse_args()
    names = [n for n in (a.only.split(",") if a.only else MODULES) if n]
    out, md = {}, ["# Report tables (generated by analysis/report.py; do not edit)\n"]
    for n in names:
        t0 = time.time()
        mod = importlib.import_module(f"report_{n}")
        data = mod.compute(a.results_dir)
        out[n] = data
        md.append(mod.tables_md(data))
        print(f"{n}: {time.time() - t0:.1f} s", file=sys.stderr)
    os.makedirs(os.path.dirname(os.path.abspath(a.json)), exist_ok=True)
    with open(a.json, "w") as f:
        json.dump(out, f, indent=1, sort_keys=True, default=lambda o: sorted(o) if isinstance(o, set) else str(o))
        f.write("\n")
    with open(a.md, "w") as f:
        f.write("\n".join(md).rstrip() + "\n")
    print(f"wrote {a.json} and {a.md}")


if __name__ == "__main__":
    main()
